"""Run static analysis tools against the labelled cases and score them.

Usage:
    python bench.py                 # run tools, print summary, write SCORECARD.md

Steps:
  1. Load the answer key (manifest.yaml).
  2. Run each tool and collect which files it flagged.
  3. Compare flagged files to the answer key -> TP / FP / FN / TN.
  4. Compute precision, recall, F1 and write SCORECARD.md.
"""
import json
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

import yaml

ROOT = Path(__file__).parent
SEVERITY_ORDER = {"LOW": 1, "MEDIUM": 2, "HIGH": 3}


# --------------------------------------------------------------- 1. answer key
def load_manifest() -> dict[str, str]:
    """Return {file_path: "vulnerable" | "safe"}."""
    data = yaml.safe_load((ROOT / "manifest.yaml").read_text())
    return {c["file"]: c["label"] for c in data["cases"]}


# ------------------------------------------------------------- 2. run the tools
# Each runner returns {file_path: [finding ids]} for every file it flagged.
# Note: arguments are passed as a LIST, never through a shell - the same rule
# we test for in cases/shell_tool.
def run_semgrep() -> dict[str, list[str]]:
    out = subprocess.run(
        ["semgrep", "--config", "rules/", "cases/", "--json", "--quiet", "--metrics=off"],
        cwd=ROOT, capture_output=True, text=True, check=False,
    )
    flagged: dict[str, list[str]] = {}
    for r in json.loads(out.stdout)["results"]:
        flagged.setdefault(r["path"], []).append(r["check_id"].split(".")[-1])
    return flagged


def run_bandit(min_severity: str = "LOW") -> dict[str, list[str]]:
    out = subprocess.run(
        ["bandit", "-r", "cases", "-f", "json", "-q"],
        cwd=ROOT, capture_output=True, text=True, check=False,
    )
    flagged: dict[str, list[str]] = {}
    for r in json.loads(out.stdout)["results"]:
        if SEVERITY_ORDER[r["issue_severity"]] >= SEVERITY_ORDER[min_severity]:
            flagged.setdefault(r["filename"], []).append(r["test_id"])
    return flagged


TOOLS = {
    "Semgrep (custom LLM rules)": run_semgrep,
    "Bandit (all severities)": lambda: run_bandit("LOW"),
    "Bandit (MEDIUM and above)": lambda: run_bandit("MEDIUM"),
}


# ----------------------------------------------------------------- 3. compare
@dataclass
class Score:
    tp: int = 0  # vulnerable and flagged   (correct alarm)
    fp: int = 0  # safe but flagged         (false alarm)
    fn: int = 0  # vulnerable but silent    (missed bug - the dangerous one)
    tn: int = 0  # safe and silent          (correct silence)
    rows: list[tuple[str, str, str, str]] = field(default_factory=list)

    @property
    def precision(self) -> float:  # of the alarms raised, how many were real?
        return self.tp / (self.tp + self.fp) if self.tp + self.fp else 0.0

    @property
    def recall(self) -> float:  # of the real bugs, how many were found?
        return self.tp / (self.tp + self.fn) if self.tp + self.fn else 0.0

    @property
    def f1(self) -> float:  # one number balancing both
        p, r = self.precision, self.recall
        return 2 * p * r / (p + r) if p + r else 0.0


def score(truth: dict[str, str], flagged: dict[str, list[str]]) -> Score:
    s = Score()
    for path, label in truth.items():
        hits = flagged.get(path, [])
        if label == "vulnerable" and hits:
            s.tp += 1; verdict = "TP"
        elif label == "vulnerable":
            s.fn += 1; verdict = "**FN**"
        elif hits:
            s.fp += 1; verdict = "**FP**"
        else:
            s.tn += 1; verdict = "TN"
        s.rows.append((path, label, ", ".join(sorted(set(hits))) or "-", verdict))
    return s


# ------------------------------------------------------------------- 4. report
def write_scorecard(results: dict[str, Score]) -> str:
    lines = ["# Scorecard", "", "Generated by `python bench.py`. Labels come from `manifest.yaml`,",
             "and every label is proven by a test in `tests/test_cases.py`.", "",
             "| Tool | TP | FP | FN | TN | Precision | Recall | F1 |",
             "|---|---|---|---|---|---|---|---|"]
    for name, s in results.items():
        lines.append(f"| {name} | {s.tp} | {s.fp} | {s.fn} | {s.tn} | "
                     f"{s.precision:.0%} | {s.recall:.0%} | {s.f1:.2f} |")
    for name, s in results.items():
        lines += ["", f"## {name}", "", "| File | Truth | Findings | Verdict |", "|---|---|---|---|"]
        lines += [f"| `{p}` | {l} | {h} | {v} |" for p, l, h, v in s.rows]
    text = "\n".join(lines) + "\n"
    (ROOT / "SCORECARD.md").write_text(text)
    return text


def main() -> int:
    truth = load_manifest()
    results = {name: score(truth, run()) for name, run in TOOLS.items()}
    write_scorecard(results)
    for name, s in results.items():
        print(f"{name:30} precision {s.precision:4.0%}  recall {s.recall:4.0%}  F1 {s.f1:.2f}")
    print("Wrote SCORECARD.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
